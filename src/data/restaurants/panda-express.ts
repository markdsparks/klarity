import type { MenuItem, RestaurantChain } from '../../types/restaurant';

// Panda Express — ingested from the chain's published nutrition disclosure
// (FDA menu-labeling rule, 21 CFR 101.11), per spec 004.
//
// Coverage note: pandaexpress.com/nutritioninformation publishes full mandated
// nutrition for every dish, but its "Allergen Info" toggle on the same page
// is a Yes/Does-Not-Contain matrix against the 9 major FDA allergens — not
// ingredient text. No per-component or whole-item ingredient statement is
// published anywhere else on the public site (checked pandaexpress.com/our-food,
// which is marketing copy with no ingredient disclosure). This is the same
// shape as Panera Bread: real mandated nutrition, no public ingredient
// statements. So this chain is modeled `nutrition-only` — every component has
// `ingredientText: null`, never fabricated, and the additives axis correctly
// shows nothing rather than a guessed statement.
//
// Because there is no published ingredient text, there is also no legitimate
// `CatalogComponent` data for entrées/sides (the type requires a non-empty
// ingredient statement — see src/types/restaurant.ts) — so Bowl/Plate combos
// are NOT modeled with spec 006 ItemSlot/CatalogComponent swaps (that would
// require fabricating ingredient text to populate the catalog). Instead each
// combo is modeled as its own standalone MenuItem whose `components` list is
// the real published entrées/side that make it up — same "whole item,
// opaque, non-removable component" pattern Panera uses, just with more than
// one component per item since Panda's own published data is naturally
// decomposed into entrée/side dishes. Nutrition for each combo is the sum of
// its real published parts (recorded as `derived from published components`,
// never estimated), which is the only way to model this chain's own
// combo-plate menu structure honestly. Two representative combos are
// included (an Orange Chicken Bowl, a Beijing Beef + Broccoli Beef Plate);
// the standalone entrées/sides that follow are the primary, most flexible
// data — anyone can compose any other Bowl/Plate/Bigger Plate manually from
// them.
//
// Scope: every standalone side, vegetable, chicken, chicken breast, beef,
// seafood, appetizer, soup, and the full soft-drink/tea/lemonade beverage
// line, all transcribed from the chain's own nutrition table, retrieved
// 2026-07. "Cub Meal" (kids) portions and the three pre-bundled Cub Meal
// combos are out of scope for this batch (smaller portions with their own
// published numbers — worth a follow-up, not required now). Regional-only
// beverage variants (PR-only Fanta Orange, TX-only Fanta Strawberry) are
// skipped as non-general-availability items.

