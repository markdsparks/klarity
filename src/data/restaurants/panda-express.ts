// Panda publishes only whole-dish mandated nutrition — no per-component
// nutrition and no ingredient text anywhere on the public site. Each
// standalone dish is modeled as one opaque, non-removable component, same
// rationale as Panera: no slots, no addOnIds, because there's no catalog
// data to support a swap or addition without fabricating ingredient text.
function wholeItemComponent(name: string) {
  return [{
    id: 'whole_item',
    name,
    removable: false,
    ingredientText: null,
    nutrition: null,
  }];
}

